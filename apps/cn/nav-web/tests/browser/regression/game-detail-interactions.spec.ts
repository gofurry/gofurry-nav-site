test('blocked adult content is inert and only confirmed mode unlocks it', async ({ detail }) => {
  await detail.open({ adult: true, width: 390 })
  const content = detail.page.locator('.blur-wrapper__content'), unlock = detail.page.locator('.blur-wrapper__unlock')
  await expect(content).toHaveAttribute('inert', '')
  await expect(content).toHaveCSS('filter', 'blur(24px)')
  await content.locator('a').focus(); await expect(content.locator('a')).not.toBeFocused()
  await detail.page.locator('[data-game-tab="intro"]').focus(); await detail.page.keyboard.press('Tab')
  await expect(unlock).toBeFocused()
  await unlock.click(); const dialog = detail.page.locator('.gf-modal--compact')
  await expect(dialog.locator('.gf-button--ghost')).toBeFocused()
  await detail.page.keyboard.press('Shift+Tab'); await expect(dialog.locator('.gf-button--primary')).toBeFocused()
  await detail.page.keyboard.press('Tab'); await expect(dialog.locator('.gf-button--ghost')).toBeFocused()
  await detail.page.keyboard.press('Escape'); await expect(dialog).toHaveCount(0); await expect(unlock).toBeFocused()
  await unlock.click(); await dialog.locator('.gf-button--ghost').click(); await expect(unlock).toBeVisible()
  await detail.tab('news'); await expect(content).toHaveAttribute('inert', '')
  await detail.tab('gallery'); await expect(detail.page.locator('video')).toHaveCount(0)
  await unlock.click(); await dialog.locator('.gf-button--primary').click()
  await expect(unlock).toHaveCount(0); await expect(content).not.toHaveAttribute('inert')
  expect(await detail.page.evaluate(() => localStorage.getItem('mode'))).toBe('nsfw')
  await expect(detail.page.locator('.game-detail-media-image')).toBeVisible()
  detail.assertQuiet()
})

test('a real video becomes ready and stops when Gallery is unmounted', async ({ detail }) => {
  await detail.open(); await detail.tab('gallery')
  const held = detail.movieGate()
  await detail.page.locator('.game-detail-thumb').first().click(); await held.wait()
  await expect(detail.page.locator('.game-detail-video-loading')).toBeVisible()
  held.release()
  const video = detail.page.locator('video')
  await expect.poll(() => video.evaluate(el => (el as HTMLVideoElement).readyState)).toBeGreaterThanOrEqual(2)
  await expect(detail.page.locator('.game-detail-video-loading')).toHaveCount(0)
  const handle = await video.elementHandle()
  await detail.tab('intro')
  expect(await handle!.evaluate(el => (el as HTMLVideoElement).paused)).toBe(true)
  await expect(video).toHaveCount(0)
  detail.failMovie(); await detail.tab('gallery'); await detail.page.locator('.game-detail-thumb').first().click()
  await expect.poll(() => video.evaluate(el => (el as HTMLVideoElement).error?.code)).toBe(4)
  await expect(detail.page.locator('.game-detail-video-loading')).toHaveCount(0)
  detail.assertQuiet()
})
