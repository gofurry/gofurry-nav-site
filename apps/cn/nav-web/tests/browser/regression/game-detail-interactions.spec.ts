test('manual keyboard tabs do not load history until activation', async ({ detail }) => {
  await detail.open()
  const tabs = detail.page.locator('[data-game-tab]')
  await tabs.first().focus(); await detail.page.keyboard.press('ArrowRight')
  await expect(detail.page.locator('[data-game-tab="insights"]')).toBeFocused()
  await expect(tabs.first()).toHaveAttribute('aria-selected', 'true')
  expect(detail.count('/games/82/insights/players')).toBe(0)
  await detail.page.keyboard.press('ArrowLeft'); await expect(tabs.first()).toBeFocused()
  await detail.page.keyboard.press('ArrowRight')
  await detail.page.keyboard.press('Enter')
  await expect(detail.page.locator('[data-player-loaded-ranges]')).toHaveAttribute('data-player-loaded-ranges', '30d')
  await detail.page.keyboard.press('End'); await expect(tabs.last()).toBeFocused()
  await detail.page.keyboard.press('Home'); await expect(tabs.first()).toBeFocused()
  await detail.page.keyboard.press('Space'); await expect(tabs.first()).toHaveAttribute('aria-selected', 'true')
  detail.assertQuiet()
})

