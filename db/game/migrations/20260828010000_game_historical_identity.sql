CREATE TABLE public.gfg_game_tracking_periods (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id bigint NOT NULL,
    appid bigint NOT NULL,
    tracked_from timestamp with time zone NOT NULL,
    tracked_until timestamp with time zone,
    tracking_basis text NOT NULL,
    opened_reason text NOT NULL,
    closed_reason text,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT gfg_game_tracking_periods_interval_check
        CHECK (tracked_until IS NULL OR tracked_until > tracked_from),
    CONSTRAINT gfg_game_tracking_periods_basis_check
        CHECK (tracking_basis IN ('explicit', 'legacy_observed')),
    CONSTRAINT gfg_game_tracking_periods_explicit_shape_check CHECK (
        tracking_basis <> 'explicit' OR appid > 0
    )
);

CREATE UNIQUE INDEX uq_gfg_game_tracking_periods_active_explicit
    ON public.gfg_game_tracking_periods (game_id)
    WHERE tracking_basis = 'explicit' AND tracked_until IS NULL;
CREATE INDEX idx_gfg_game_tracking_periods_identity_time
    ON public.gfg_game_tracking_periods (game_id, appid, tracked_from, tracked_until);
CREATE INDEX idx_gfg_game_tracking_periods_time
    ON public.gfg_game_tracking_periods (tracked_from, tracked_until);

-- Build conservative, closed legacy identity periods from retained evidence.
-- AppID transitions are ordered by the first observation; the next identity's
-- first observation is the previous identity's exclusive upper bound.
WITH migration_clock AS (
    SELECT transaction_timestamp() AS cutover
), evidence AS (
    SELECT game_id, appid, collected_at AS observed_at
    FROM public.gfg_game_player_counts
    WHERE appid > 0
    UNION ALL
    SELECT game_id, appid, started_at
    FROM public.gfg_collection_task_results
    WHERE appid > 0
), identity_bounds AS (
    SELECT game_id, appid, min(observed_at) AS first_observed_at,
           max(observed_at) AS last_observed_at
    FROM evidence
    GROUP BY game_id, appid
), ordered AS (
    SELECT game_id, appid, first_observed_at, last_observed_at,
           lead(first_observed_at) OVER (
               PARTITION BY game_id ORDER BY first_observed_at, appid
           ) AS next_identity_at
    FROM identity_bounds
)
INSERT INTO public.gfg_game_tracking_periods (
    game_id, appid, tracked_from, tracked_until, tracking_basis,
    opened_reason, closed_reason
)
SELECT game_id,
       appid,
       first_observed_at,
       GREATEST(
           first_observed_at + interval '1 microsecond',
           LEAST(
               COALESCE(next_identity_at, migration_clock.cutover),
               migration_clock.cutover
           )
       ),
       'legacy_observed',
       'historical_evidence',
       'p0.2_quality_cutover'
FROM ordered
CROSS JOIN migration_clock
WHERE first_observed_at < migration_clock.cutover;

-- Current identity starts at the rollout transaction; it is never projected
-- backwards over legacy evidence.
INSERT INTO public.gfg_game_tracking_periods (
    game_id, appid, tracked_from, tracking_basis, opened_reason
)
SELECT id, appid, transaction_timestamp(), 'explicit', 'p0.2_rollout'
FROM public.gfg_game;

