-- A durable player run has exactly one canonical raw result per Game. Rank any
-- pre-contract duplicates by agreement with the Task Result, observation-time
-- proximity, and then stable id. The audit count is visible in Goose output.
-- +goose StatementBegin
DO $audit$
DECLARE
    duplicate_count bigint;
BEGIN
    SELECT COALESCE(sum(row_count - 1), 0)
    INTO duplicate_count
    FROM (
        SELECT count(*) AS row_count
        FROM public.gfg_game_player_counts
        WHERE run_id <> ''
        GROUP BY run_id, game_id
        HAVING count(*) > 1
    ) duplicates;
    IF duplicate_count > 0 THEN
        RAISE NOTICE 'P0.2 Game raw migration will remove % duplicate Run/Game row(s)', duplicate_count;
    END IF;
END;
$audit$;
-- +goose StatementEnd

WITH ranked AS (
    SELECT raw.id,
           row_number() OVER (
               PARTITION BY raw.run_id, raw.game_id
               ORDER BY
                   CASE WHEN result.status IS NOT NULL AND raw.status = result.status THEN 0 ELSE 1 END,
                   abs(extract(epoch FROM (raw.collected_at - COALESCE(result.ended_at, result.started_at, raw.collected_at)))),
                   raw.id DESC
           ) AS canonical_rank
    FROM public.gfg_game_player_counts raw
    LEFT JOIN LATERAL (
        SELECT candidate.status, candidate.started_at, candidate.ended_at
        FROM public.gfg_collection_task_results candidate
        WHERE candidate.run_id = raw.run_id
          AND candidate.game_id = raw.game_id
          AND candidate.task_type = 'players'
        ORDER BY candidate.id DESC
        LIMIT 1
    ) result ON true
    WHERE raw.run_id <> ''
)
DELETE FROM public.gfg_game_player_counts raw
USING ranked
WHERE ranked.id = raw.id AND ranked.canonical_rank > 1;

