-- +goose StatementBegin
DO $validation$
DECLARE
    old_runs bigint;
    new_runs bigint;
    old_results bigint;
    new_results bigint;
BEGIN
    SELECT count(*) INTO old_runs FROM public.gfg_game_v2_collect_runs;
    SELECT count(*) INTO new_runs
      FROM public.gfg_collection_runs r
      JOIN public.gfg_collection_jobs j ON j.id = r.job_id
     WHERE j.trigger = 'legacy_import' AND j.requested_by = 'migration';
    SELECT count(*) INTO old_results FROM public.gfg_game_v2_collect_task_results;
    SELECT count(*) INTO new_results
      FROM public.gfg_collection_task_results tr
      JOIN public.gfg_collection_runs r ON r.id = tr.run_id
      JOIN public.gfg_collection_jobs j ON j.id = r.job_id
     WHERE j.trigger = 'legacy_import' AND j.requested_by = 'migration';

    IF old_runs <> new_runs THEN
        RAISE EXCEPTION 'legacy Game run migration mismatch: old %, new %', old_runs, new_runs;
    END IF;
    IF old_results <> new_results THEN
        RAISE EXCEPTION 'legacy Game task-result migration mismatch: old %, new %', old_results, new_results;
    END IF;
END;
$validation$;
-- +goose StatementEnd

