CREATE TEMPORARY TABLE gfg_legacy_run_job_map (
    run_id text PRIMARY KEY,
    job_id bigint NOT NULL UNIQUE
) ON COMMIT DROP;

-- +goose StatementBegin
DO $migration$
DECLARE
    legacy_run record;
    migrated_job_id bigint;
    migrated_status text;
    migrated_tasks text[];
BEGIN
    FOR legacy_run IN
        SELECT * FROM public.gfg_game_v2_collect_runs ORDER BY started_at, id
    LOOP
        migrated_status := CASE
            WHEN legacy_run.status IN ('success', 'partial', 'failed', 'skipped', 'canceled') THEN legacy_run.status
            WHEN legacy_run.status = 'running' THEN 'failed'
            ELSE 'failed'
        END;
        migrated_tasks := array_remove(regexp_split_to_array(legacy_run.task_type, '\s*,\s*'), '');
        IF cardinality(migrated_tasks) = 0 OR migrated_tasks IS NULL THEN
            migrated_tasks := ARRAY['details']::text[];
        END IF;

        INSERT INTO public.gfg_collection_jobs (
            job_key, trigger, scope_type, tasks, priority, concurrency_key,
            status, requested_by, created_at, updated_at, completed_at
        ) VALUES (
            'game.legacy.' || legacy_run.id,
            'legacy_import',
            'all',
            migrated_tasks,
            0,
            'steam',
            migrated_status,
            'migration',
            legacy_run.started_at,
            COALESCE(legacy_run.ended_at, legacy_run.started_at),
            COALESCE(legacy_run.ended_at, legacy_run.started_at)
        ) RETURNING id INTO migrated_job_id;

        INSERT INTO gfg_legacy_run_job_map(run_id, job_id)
        VALUES (legacy_run.id, migrated_job_id);
    END LOOP;
END;
$migration$;
-- +goose StatementEnd

INSERT INTO public.gfg_collection_runs (
    id, job_id, attempt_no, collector_instance_id, status, started_at, ended_at,
    expected_count, attempted_count, success_count, partial_count, failure_count,
    skipped_count, duration_ms, error_kind, error_message
)
SELECT
    old.id,
    map.job_id,
    1,
    'legacy-import',
    CASE
        WHEN old.status IN ('success', 'partial', 'failed', 'canceled') THEN old.status
        WHEN old.status = 'running' THEN 'failed'
        ELSE 'failed'
    END,
    old.started_at,
    COALESCE(old.ended_at, old.started_at),
    old.total_count,
    old.success_count + old.partial_count + old.failed_count,
    old.success_count,
    old.partial_count,
    old.failed_count,
    old.skipped_count,
    GREATEST(old.duration_millis, 0),
    CASE WHEN old.status = 'running' THEN 'legacy_incomplete' ELSE old.error_kind END,
    CASE WHEN old.status = 'running' THEN 'Legacy running record was finalized during control-plane migration.' ELSE old.error_message END
FROM public.gfg_game_v2_collect_runs old
JOIN gfg_legacy_run_job_map map ON map.run_id = old.id;

