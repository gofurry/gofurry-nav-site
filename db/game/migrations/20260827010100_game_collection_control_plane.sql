CREATE TABLE public.gfg_collection_schedules (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_key text NOT NULL UNIQUE,
    name text NOT NULL,
    enabled boolean NOT NULL DEFAULT true,
    schedule_kind text NOT NULL CHECK (schedule_kind IN ('cron', 'interval')),
    cron_expression text,
    interval_seconds bigint,
    anchor_at timestamp with time zone,
    timezone text NOT NULL,
    misfire_policy text NOT NULL CHECK (misfire_policy IN ('skip', 'catch_up_once')),
    misfire_grace_seconds integer NOT NULL DEFAULT 0 CHECK (misfire_grace_seconds >= 0),
    overlap_policy text NOT NULL DEFAULT 'skip' CHECK (overlap_policy = 'skip'),
    priority integer NOT NULL CHECK (priority >= 0),
    concurrency_key text NOT NULL,
    version bigint NOT NULL DEFAULT 1 CHECK (version > 0),
    effective_from timestamp with time zone NOT NULL DEFAULT now(),
    last_materialized_for timestamp with time zone,
    next_scheduled_for timestamp with time zone,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT gfg_collection_schedules_shape_check CHECK (
        (schedule_kind = 'cron' AND cron_expression IS NOT NULL AND btrim(cron_expression) <> '' AND interval_seconds IS NULL AND anchor_at IS NULL)
        OR
        (schedule_kind = 'interval' AND cron_expression IS NULL AND interval_seconds > 0 AND anchor_at IS NOT NULL)
    )
);

CREATE TABLE public.gfg_collection_jobs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id bigint REFERENCES public.gfg_collection_schedules(id) ON DELETE SET NULL,
    schedule_version bigint,
    job_key text NOT NULL,
    trigger text NOT NULL CHECK (trigger IN ('scheduled', 'manual', 'startup_catchup', 'entity_created', 'entity_changed', 'legacy_import')),
    scope_type text NOT NULL CHECK (scope_type IN ('all', 'game')),
    scope_id bigint,
    target text,
    tasks text[] NOT NULL CHECK (cardinality(tasks) > 0),
    priority integer NOT NULL CHECK (priority >= 0),
    concurrency_key text NOT NULL,
    scheduled_for timestamp with time zone,
    status text NOT NULL CHECK (status IN ('queued', 'running', 'success', 'partial', 'failed', 'skipped', 'missed', 'canceled')),
    requested_by text NOT NULL,
    dedupe_key text,
    claimed_by text,
    lease_until timestamp with time zone,
    cancel_requested_at timestamp with time zone,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone NOT NULL DEFAULT now(),
    completed_at timestamp with time zone,
    CONSTRAINT gfg_collection_jobs_scope_check CHECK (
        (scope_type = 'all' AND scope_id IS NULL AND target IS NULL)
        OR
        (scope_type = 'game' AND scope_id IS NOT NULL AND target IS NULL)
    ),
    CONSTRAINT gfg_collection_jobs_schedule_check CHECK (
        trigger <> 'scheduled'
        OR (schedule_id IS NOT NULL AND schedule_version IS NOT NULL AND scheduled_for IS NOT NULL)
    ),
    CONSTRAINT gfg_collection_jobs_claim_check CHECK (
        (status = 'running' AND claimed_by IS NOT NULL AND lease_until IS NOT NULL)
        OR status <> 'running'
    )
);

CREATE TABLE public.gfg_collector_instances (
    instance_id text PRIMARY KEY,
    collector_id text NOT NULL,
    hostname text NOT NULL,
    version text NOT NULL,
    commit_sha text NOT NULL,
    capabilities text[] NOT NULL CHECK (cardinality(capabilities) > 0),
    started_at timestamp with time zone NOT NULL,
    last_heartbeat_at timestamp with time zone NOT NULL,
    stopped_at timestamp with time zone
);

CREATE TABLE public.gfg_collection_runs (
    id text PRIMARY KEY,
    job_id bigint NOT NULL REFERENCES public.gfg_collection_jobs(id) ON DELETE CASCADE,
    attempt_no integer NOT NULL CHECK (attempt_no > 0),
    collector_instance_id text NOT NULL REFERENCES public.gfg_collector_instances(instance_id),
    status text NOT NULL CHECK (status IN ('running', 'success', 'partial', 'failed', 'canceled')),
    scheduled_for timestamp with time zone,
    started_at timestamp with time zone NOT NULL,
    ended_at timestamp with time zone,
    expected_count integer NOT NULL DEFAULT 0 CHECK (expected_count >= 0),
    attempted_count integer NOT NULL DEFAULT 0 CHECK (attempted_count >= 0),
    success_count integer NOT NULL DEFAULT 0 CHECK (success_count >= 0),
    partial_count integer NOT NULL DEFAULT 0 CHECK (partial_count >= 0),
    failure_count integer NOT NULL DEFAULT 0 CHECK (failure_count >= 0),
    skipped_count integer NOT NULL DEFAULT 0 CHECK (skipped_count >= 0),
    schedule_delay_ms bigint NOT NULL DEFAULT 0 CHECK (schedule_delay_ms >= 0),
    duration_ms bigint NOT NULL DEFAULT 0 CHECK (duration_ms >= 0),
    error_kind text NOT NULL DEFAULT '',
    error_message text NOT NULL DEFAULT '',
    UNIQUE (job_id, attempt_no),
    CONSTRAINT gfg_collection_runs_counter_balance_check CHECK (
        attempted_count = success_count + partial_count + failure_count
    )
);

CREATE TABLE public.gfg_collection_task_results (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id text NOT NULL REFERENCES public.gfg_collection_runs(id) ON DELETE CASCADE,
    task_type text NOT NULL CHECK (task_type IN ('details', 'news', 'players')),
    game_id bigint NOT NULL,
    appid bigint NOT NULL,
    status text NOT NULL CHECK (status IN ('success', 'partial', 'failed', 'skipped')),
    upstream_status_code integer NOT NULL DEFAULT 0,
    traffic_bucket text NOT NULL DEFAULT '',
    retry_count integer NOT NULL DEFAULT 0 CHECK (retry_count >= 0),
    duration_ms bigint NOT NULL DEFAULT 0 CHECK (duration_ms >= 0),
    error_kind text NOT NULL DEFAULT '',
    error_message text NOT NULL DEFAULT '',
    started_at timestamp with time zone NOT NULL,
    ended_at timestamp with time zone,
    UNIQUE (run_id, task_type, game_id)
);

